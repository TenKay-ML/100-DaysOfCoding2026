public class belajarjava {

    public static void main(String[] args) {
        
        byte A = 15;
        short B = A;
        int C = B;
        long D = C;
        float E = D;
        double F = E;

        System.out.println("nilai awal byte \t\t\t= "+ A);
        System.out.println("byte setelah di konversi ke short \t= "+ B);
        System.out.println("short setelah di konversi ke integer \t= "+ C);
        System.out.println("integer setelah di konversi ke long \t= "+ D);
        System.out.println("long setelah di konversi ke float \t= "+ E);
        System.out.println("float setelah di konversi ke double \t= "+ F);

        
    }
}
